import { render, screen } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";
import ResearchPage from "./page";

afterEach(() => vi.unstubAllGlobals());

function stub(body: unknown) {
  vi.stubGlobal("fetch", vi.fn().mockResolvedValue({ json: () => Promise.resolve(body) }));
}

describe("/research (Phase 8)", () => {
  it("renders the architecture and the numbers from the evaluation files", async () => {
    stub({
      dataset: {
        total_documents: 3640,
        qa_benchmark: { total: 45275 },
        near_duplicate_rate: 0,
        train_test_leakage_count: 0,
      },
      evaluation: {
        extraction: { cross_domain: { ner: { micro: { f1: 0.9962 } } } },
        qa: { factual: { total: 10, accuracy: 0.9, evidenceAccuracy: 0.9 } },
        consistency: { perCategory: {} },
      },
    });
    render(<ResearchPage />);
    expect(screen.getByTestId("architecture")).toHaveTextContent(/Domain detection/);
    expect(screen.getByTestId("architecture-diagram")).toBeInTheDocument();
    for (const t of [
      "Problem",
      "Semantic fact layer",
      "Privacy / local-first design",
      "Future work",
    ]) {
      expect(screen.getByRole("heading", { name: new RegExp(t) })).toBeInTheDocument();
    }
    expect(await screen.findByText("3640")).toBeInTheDocument();
    expect(screen.getByText("99.6%")).toBeInTheDocument();
    expect(screen.getAllByText("90.0%")).toHaveLength(2);
    expect(
      screen.getByText(/synthetic documents generated by the same project/),
    ).toBeInTheDocument();
  });

  it("says so when no evaluation has been run - no placeholder numbers", async () => {
    stub({ dataset: null, evaluation: null });
    render(<ResearchPage />);
    expect(await screen.findByText("The evaluation has not been run yet.")).toBeInTheDocument();
    expect(screen.getByText("No dataset report has been generated yet.")).toBeInTheDocument();
  });
});
