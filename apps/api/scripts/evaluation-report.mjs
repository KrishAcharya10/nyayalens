// Renders docs/evaluation.md from the evaluation harness's results object
// (scripts/evaluate-v3.mjs). Every number in the document comes from
// `results` or the dataset report - nothing is typed in by hand.

const f = (v) => (v === null || v === undefined ? "n/a" : Number(v).toFixed(4));
const pc = (v) => (v === null || v === undefined ? "n/a" : `${(v * 100).toFixed(1)}%`);
const row = (cells) => `| ${cells.join(" | ")} |`;
const table = (head, rows) => [row(head), row(head.map(() => "---")), ...rows.map(row)].join("\n");

export function renderEvaluationMarkdown(results, dataset) {
  const out = [];
  const push = (...l) => {
    for (const x of l) out.push(x, "");
  };

  push(
    "# NyayaLens Phase 8 - evaluation",
    "> Generated by `apps/api/scripts/evaluate-v3.mjs` - do not edit by hand; re-run the script.",
    `Generated: ${results.generatedAt}  `,
    `Dataset: \`${results.dataset}\`` +
      (dataset
        ? ` (generator ${dataset.generator_version}, seed ${dataset.seed}, ${dataset.total_documents} documents, ${dataset.qa_benchmark?.total ?? "n/a"} QA items)`
        : ""),
  );

  push(
    "## How to read these numbers",
    "- **Synthetic only.** Every document was produced by the project's own generator " +
      "(`research/generator/v3`). The extraction rules were written by the same project, " +
      "against the same generator's surface forms. These numbers show the system handles the " +
      "forms it was built for; they are **not** an estimate of accuracy on real-world documents.",
    "- **Development data vs. final data.** Rules were developed and tuned against a seed-2026 " +
      "dataset (whose test split was inspected while tuning) and a seed-99 development dataset. " +
      "The final numbers below are on a freshly generated dataset (see the seed above) that was " +
      "not inspected before this run. It still comes from the same templates and value pools, " +
      "so it is a check against overfitting to specific documents, not to the generator.",
    "- **Held-out templates.** Test documents use held-out clause templates on 50% of " +
      "draws; the generator's validator reports 0 template leakage and 0 train/test " +
      "near-duplicates (MinHash, Jaccard >= 0.8).",
    "- **No trained model.** Every number is from the rule-based pipeline " +
      "(`model_source = RULE_BASED`). No model was trained or fine-tuned in Phase 8.",
    "- **Same code as production.** The harness calls the same functions the upload pipeline " +
      "calls (NER, clause classification, semantic analysis, consistency, risk checks, domain " +
      "detection, structured QA), in memory, on each document's raw text. OCR is not exercised.",
  );

  // Detection
  push("## Domain detection", "Deterministic signal counts; no probabilities are produced.");
  push(
    table(
      ["Split", "Documents", "Domain accuracy", "Document-type accuracy"],
      Object.entries(results.domainDetection).map(([k, v]) => [
        k,
        v.documents,
        pc(v.domainAccuracy),
        pc(v.documentTypeAccuracy),
      ]),
    ),
    'The cross-domain split uses generic titles ("AGREEMENT"), so document-type accuracy ' +
      "there measures recovery from wording alone.",
  );

  // Extraction
  push("## Extraction");
  const splits = Object.entries(results.extraction);
  push(
    table(
      ["Split", "Docs", "Entity P / R / F1", "Clause P / R / F1", "Relation P / R / F1"],
      splits.map(([k, v]) => [
        k,
        v.documents,
        `${f(v.ner.micro.precision)} / ${f(v.ner.micro.recall)} / ${f(v.ner.micro.f1)}`,
        `${f(v.clauses.micro.precision)} / ${f(v.clauses.micro.recall)} / ${f(v.clauses.micro.f1)}`,
        `${f(v.relations.micro.precision)} / ${f(v.relations.micro.recall)} / ${f(v.relations.micro.f1)}`,
      ]),
    ),
    "Entities are matched on exact span and label; clauses on type and overlapping span; " +
      "relations on (subject label, relation type, object normalized value).",
  );
  const [firstName, first] = splits[0];
  push(`### Per domain (${firstName} split, F1)`);
  push(
    table(
      ["Domain", "Entities", "Clauses", "Relations"],
      Object.keys(first.ner.perDomain).map((d) => [
        d,
        f(first.ner.perDomain[d]?.f1),
        f(first.clauses.perDomain?.[d]?.f1),
        f(first.relations.perDomain?.[d]?.f1),
      ]),
    ),
  );
  push("### Obligations");
  push(
    table(
      [
        "Split",
        "Ground truth",
        "Predicted",
        "Actor+action P / R / F1",
        "Evidence recall",
        "Actor acc.",
        "Action acc.",
      ],
      splits.map(([k, v]) => [
        k,
        v.obligations.groundTruth,
        v.obligations.predicted,
        `${f(v.obligations.actorActionF1.precision)} / ${f(v.obligations.actorActionF1.recall)} / ${f(v.obligations.actorActionF1.f1)}`,
        pc(v.obligations.evidenceRecall),
        pc(v.obligations.actorAccuracy),
        pc(v.obligations.actionAccuracy),
      ]),
    ),
    "Actor/action accuracy is measured on obligations whose evidence sentence matched.",
  );
  push("### Normalization (values whose span was extracted)");
  push(
    table(
      ["Split", ...Object.keys(first.normalization)],
      splits.map(([k, v]) => [
        k,
        ...Object.keys(first.normalization).map(
          (t) => `${pc(v.normalization[t]?.accuracy)} (${v.normalization[t]?.total ?? 0})`,
        ),
      ]),
    ),
  );

  // Consistency
  const c = results.consistency;
  push(
    "## Consistency engine",
    "Adversarial documents carry one injected inconsistency; each has a control twin generated " +
      "from the same seed without it.",
  );
  push(
    table(
      ["Category", "Detected", "Evidence correct", "Control false positives"],
      Object.entries(c.perCategory).map(([k, v]) => [
        k,
        `${v.detected}/${v.adversarial} (${pc(v.detectionRate)})`,
        `${v.evidenceCorrect}/${v.detected} (${pc(v.evidenceCorrectness)})`,
        `${v.controlFalsePositives}/${v.controls} (${pc(v.controlFalsePositiveRate)})`,
      ]),
    ),
    `Ordinary test documents with any consistency finding: ${c.ordinaryTestDocuments.withAnyFinding}/${c.ordinaryTestDocuments.documents} (${pc(c.ordinaryTestDocuments.rate)}).`,
  );

  // Risks
  const r = results.risks;
  push("## Risk checks (ordinary test documents)");
  push(
    table(
      ["Category", "P", "R", "F1", "TP / FP / FN"],
      [
        ...Object.entries(r.perCategory).map(([k, v]) => [
          k,
          f(v.precision),
          f(v.recall),
          f(v.f1),
          `${v.tp} / ${v.fp} / ${v.fn}`,
        ]),
        [
          "MISSING_CLAUSE",
          f(r.missingClause.precision),
          f(r.missingClause.recall),
          f(r.missingClause.f1),
          `${r.missingClause.tp} / ${r.missingClause.fp} / ${r.missingClause.fn}`,
        ],
      ],
    ),
  );
  const fps = Object.entries(r.missingClause.falsePositivesByDocumentTypeAndClause ?? {});
  if (fps.length) {
    push(
      "Missing-clause false positives by document type and clause (on the development set, " +
        "every such case was a clause that is present but whose heading the classifier did not " +
        "recognise): " +
        fps.map(([k, n]) => `${k} (${n})`).join(", ") +
        ".",
    );
  }
  push(
    "Per-category counts are small (a category is only scored on documents where the generator " +
      "injected it or the system flagged it), so treat these as indicative.",
  );

  // Counterfactual
  const cf = results.counterfactual;
  push(
    "## Counterfactual sensitivity",
    `${cf.pairs} document pairs differ in one value (e.g. the rent). The change is reflected in extraction ` +
      `for ${cf.reflectedInExtraction}/${cf.expectedChanges} expected changes (${pc(cf.rate)}).`,
  );

  // QA
  push(
    "## Question answering",
    "Questions come from the generator's QA benchmark (test, adversarial and control splits). " +
      "Structured answering is tried first, as in `runAsk`; evidence is correct when a cited span " +
      "overlaps a ground-truth mention of the asked field.",
  );
  push(
    table(
      ["Type", "Items", "Answer accuracy", "Evidence accuracy", "Answered structurally"],
      Object.entries(results.qa).map(([k, v]) => [
        k,
        v.total,
        pc(v.accuracy),
        pc(v.evidenceAccuracy),
        pc(v.answeredStructurally),
      ]),
    ),
    "Unanswerable questions are correct only when the answer is NOT_SUFFICIENT. The QA " +
      "benchmark's question phrasings come from the generator, so these figures do not cover " +
      "free-form user questions; the retrieval fallback is not separately scored here (see " +
      "`apps/api/rag_eval/` for the Phase 7A retrieval evaluation).",
  );

  // v1
  push("## Regression: Phase 6 adversarial set (v1)");
  push(
    table(
      ["Category", "Detected", "Control false positives", "Other-category flags on positives"],
      Object.entries(results.v1AdversarialRegression).map(([k, v]) => [
        k,
        `${v.detected}/${v.positives}`,
        `${v.controlFalsePositives}/${v.controls}`,
        v.crossCategoryFalsePositivesOnPositives,
      ]),
    ),
  );

  push(
    "## Known limitations",
    "- Real-document performance is unmeasured. Indian agreements vary far more in layout, " +
      "wording, OCR quality and language mixing than any generator.",
    "- Clause classification is heading-based: a clause with an unusual heading is missed, which " +
      "then also produces a false MISSING_CLAUSE finding.",
    "- Obligation extraction is sentence-level and pattern-based; obligations spread over several " +
      "sentences, or stated without a modal verb, are missed.",
    "- Legal reference metadata is UNVERIFIED and is never presented as legal applicability " +
      "(docs/legal_reference_policy.md).",
  );
  return out.join("\n");
}
