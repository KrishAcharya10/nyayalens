"""Writes docs/dataset_card.md from a dataset quality report (generate_v3.py --write-card)."""

from pathlib import Path


def _table(mapping: dict, key: str, value: str = "Count") -> str:
    rows = "\n".join(f"| {k} | {v} |" for k, v in sorted(mapping.items(), key=lambda kv: (-kv[1], kv[0])))
    return f"| {key} | {value} |\n|---|---|\n{rows}"


def write_dataset_card(report: dict, path: Path) -> None:
    per_domain = report["documents_per_domain_and_split"]
    split_cols = ["train", "dev", "test", "adversarial", "control", "counterfactual", "cross_domain"]
    domain_rows = "\n".join(
        f"| {d} | " + " | ".join(str(s.get(c, 0)) for c in split_cols) + f" | {sum(s.values())} |"
        for d, s in sorted(per_domain.items()))
    entity_total = sum(sum(v.values()) for v in report["entities_per_label"].values())
    relation_total = sum(sum(v.values()) for v in report["relations_per_type"].values())
    obligation_total = sum(sum(v.values()) for v in report["obligations_per_action"].values())
    qa = report["qa_benchmark"]
    path.write_text(f"""# NyayaLens synthetic dataset v3 - dataset card

Generated by `research/generator/generate_v3.py` (generator {report['generator_version']}, seed {report['seed']}).
Every number below is copied from `research/data/reports/dataset_quality.json`, written by the same run.
The dataset itself (`research/data/synthetic_v3/`) is git-ignored and regenerates byte-for-byte from the seed.

## What this is - and is not

- **Fully synthetic, template-generated** Indian legal documents for seven domains. Not scraped, not
  derived from real agreements, and **not a statement of what the law is**. Some documents contain
  deliberately unfair or inconsistent clauses, for testing.
- Labels are **exact by construction**: every labeled span is written by the generator at a known
  offset and checked before the document is accepted (`research/generator/v3/validate.py`).
- Results on this data are synthetic-only and must never be presented as real-world performance.
  `research/data/real/` is still empty.

## Composition

{report['total_documents']} documents, average {report['average_document_length_words']} words.

| Domain | train | dev | test | adversarial | control | counterfactual | cross_domain | total |
|---|---|---|---|---|---|---|---|---|
{domain_rows}

{_table(report['documents_per_document_type'], 'Document type')}

{_table(report['difficulty_distribution'], 'Difficulty')}

**EASY**: canonical "1. HEADING" layout, fewer optional clauses. **MEDIUM**: four heading styles,
alternative party terms, cross-references, restated values. **HARD**: all six heading styles
(including inline and roman-numeral articles), hard line-wraps mid-sentence (as in PDF text),
co-purchasers, more annexures, more restatements and cross-references.

## Annotation layers (per document)

1. raw text  2. entities (with core type)  3. semantic roles (entity label = role, `core_type` = type)
4. relations  5. clauses  6. obligations (actor, action, amount, deadline, frequency, condition, evidence)
7. temporal facts (normalized ISO dates / durations)  8. financial facts (INR amounts)
9. semantic facts (subject-predicate-object with qualifiers and evidence)  10. risks
11. consistency expectations - plus the QA benchmark.

Totals: {entity_total} entity mentions, {relation_total} relations, {obligation_total} obligations.
Per-label counts: `entities_per_label`, `relations_per_type`, `obligations_per_action` in the quality report.

## Splits (template-aware)

Train and dev never use the held-out quarter of any template pool with 3+ variants (phrasings,
headings, titles). Test documents draw from held-out variants about half the time
({report['template_distribution']['test_documents_using_heldout_templates']} test documents use at
least one), so test scores measure generalisation to unseen wording.
`splits/mixed_test.txt` pools every domain's test split; `splits/cross_domain_test.txt` lists
HARD documents with generic titles ("AGREEMENT", "DEED"), so domain detection must use content.

## Adversarial, control and counterfactual sets

- **Adversarial / control pairs**: each pair shares a seed. The adversarial document contains one injected
  inconsistency (e.g. sale consideration differs between the consideration clause and the schedule;
  advance + balance != consideration; balance payable by the seller). Its control is identical except
  the inconsistency is absent. Each record carries `expected_risk`, `consistency_expectations[].expected_evidence`
  and `expected_control_result` (FLAG / NO_FLAG).
  Expectations: {report['consistency_expectations']}.
- **Counterfactual pairs** differ in exactly one fact (e.g. notice period 30 -> 60 days); `counterfactual.expected_changes`
  lists the changed facts, computed automatically by diffing the two documents' annotations.
- **Risks** (unfair-clause variants in ordinary documents, plus derived MISSING_CLAUSE):
  {report['risk_distribution']}. Unfair variants are phrased independently of the risk engine's regexes.

## QA benchmark

{qa['total']} questions (`qa/qa_benchmark.jsonl`), generated only from ground-truth annotations,
each with expected answer and evidence span(s): {qa['by_type']}.
Unanswerable questions ask for a field the document lacks, or a field from another domain.

## Quality report (this run)

| Check | Value |
|---|---|
| Critical validation failures | {report['critical_failures']} |
| Invalid annotations | {report['invalid_annotation_count']} |
| Exact-duplicate rate | {report['duplicate_rate']} |
| Near-duplicate pairs (word 5-gram Jaccard >= 0.9, designed pairs excluded) | {report['near_duplicate_pairs']} |
| Train/test near-duplicate leakage | {report['train_test_leakage_count']} |
| Train/test pairs with Jaccard >= 0.8 | {report['train_test_pairs_jaccard_ge_0.8']} |
| Held-out templates in train/dev | {report['template_leakage_count']} |
| Distinct template combinations | {report['template_distribution']['distinct_template_ids']} |

The validator also fails generation if any adversarial document does not actually violate its rule,
or any control or ordinary document violates one.

## Known limitations

- Template-generated: far more varied than v1/v2, still far narrower than real drafting.
- English only; no bilingual deeds. Simulated scans are cleaner than real photocopies.
- Value ranges are plausible, not sampled from real statistics.
- One author wrote the generators, the ontology and the extraction rules evaluated against them;
  held-out templates reduce but do not remove that bias.
- `nda_msa` never produces a `SERVE_NOTICE` obligation (its termination terms are mutual rights).
""", encoding="utf-8", newline="\n")
