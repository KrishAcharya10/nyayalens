// The Phase 6 build prompt's addendum: "evaluate the risk engine on a
// clean non-adversarial control set drawn from the ordinary synthetic
// documents, and report its overall false-positive rate separately from
// adversarial-category performance. Do not use adversarial documents as
// the only evidence for false-positive behavior."
//
// Runs the risk engine directly (not through the HTTP pipeline - these
// documents were uploaded during Phase 4B, before risk_engine existed as a
// pipeline stage, so they have no persisted Risk rows yet) against every
// ordinary synthetic document under the Phase 4B eval account
// (phase4b-eval@nyayalens.local) and reports what fraction produced at
// least one risk finding, plus a per-category breakdown. These documents
// were generated by research/generator/generator.py with no injected risk
// condition, so - to the extent the ordinary generator's own template
// language doesn't happen to resemble one of the five risk patterns - any
// finding here is a false positive.
//
// Usage (from apps/api - imports TypeScript source via tsx):
//   dotenv -e ../../.env -- tsx scripts/evaluate-ordinary-control-fp.mjs
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getPrismaClient } from "@nyayalens/db";
import { runRiskEngine } from "../src/risk/runRiskEngine.js";

const prisma = getPrismaClient();
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT_PATH = path.resolve(
  __dirname,
  "../../../research/data/adversarial/ordinary_control_fp_results.json",
);

async function main() {
  const documents = await prisma.document.findMany({
    where: { owner: { email: "phase4b-eval@nyayalens.local" } },
    select: { id: true, documentType: true },
  });

  console.log(
    `[evaluate-ordinary-control-fp] ${documents.length} ordinary synthetic documents found`,
  );

  let withAnyFinding = 0;
  const perCategoryCounts = {};
  const flaggedDocIds = [];

  for (let i = 0; i < documents.length; i++) {
    const doc = documents[i];
    const findings = await runRiskEngine(doc.id, "RULE_BASED");
    if (findings.length > 0) {
      withAnyFinding++;
      flaggedDocIds.push({ documentId: doc.id, categories: findings.map((f) => f.category) });
    }
    for (const f of findings) {
      perCategoryCounts[f.category] = (perCategoryCounts[f.category] ?? 0) + 1;
    }
    if ((i + 1) % 50 === 0 || i === documents.length - 1) {
      console.log(`[evaluate-ordinary-control-fp] ${i + 1}/${documents.length} processed`);
    }
  }

  const report = {
    generated_at: new Date().toISOString(),
    n_documents: documents.length,
    n_documents_with_any_finding: withAnyFinding,
    overall_false_positive_rate: documents.length > 0 ? withAnyFinding / documents.length : null,
    findings_per_category: perCategoryCounts,
    flagged_document_ids: flaggedDocIds,
  };

  writeFileSync(OUT_PATH, JSON.stringify(report, null, 2), "utf-8");
  console.log(JSON.stringify(report, null, 2));
  await prisma.$disconnect();
}

main().catch(async (err) => {
  console.error("[evaluate-ordinary-control-fp] Fatal error:", err);
  await prisma.$disconnect();
  process.exitCode = 1;
});
